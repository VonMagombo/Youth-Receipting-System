#!/usr/bin/env python3
"""Builds src/assets/receiptFont.ts: DejaVu Sans Mono (regular + bold) as small embedded WOFF2 fonts.

Receipts are drawn by the phone's WebView, and Android ships no Monaco, DejaVu or OCR font, so the
font travels inside the receipt HTML. Subsetting to Latin keeps each receipt light; any character
outside the subset falls back to the phone's own monospace font.

Needs fontTools + brotli (not an app dependency, only for regenerating):
    python3 -m venv /tmp/fontenv && /tmp/fontenv/bin/pip install fonttools brotli
    /tmp/fontenv/bin/python scripts/build-receipt-font.py [path/to/dejavu/fonts]
Default font path is Debian/Ubuntu's fonts-dejavu-core. License: assets/fonts/LICENSE-DejaVu.txt.
"""
import base64
import io
import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu")
OUT = ROOT / "src/assets/receiptFont.ts"

# Basic Latin, Latin-1, Latin Extended-A/B (names with accents), and the punctuation the templates use:
# dashes, curly quotes, bullet, middle dot, ellipsis.
UNICODES = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x250))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026]
)


def woff2_b64(path: pathlib.Path) -> str:
    font = TTFont(path)
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]  # keep copyright and license records inside the font
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def main() -> None:
    regular = woff2_b64(SRC / "DejaVuSansMono.ttf")
    bold = woff2_b64(SRC / "DejaVuSansMono-Bold.ttf")
    OUT.write_text(
        "// Generated by scripts/build-receipt-font.py from DejaVu Sans Mono (Latin subset, WOFF2).\n"
        "// Do not edit by hand. License: assets/fonts/LICENSE-DejaVu.txt.\n"
        f"export const RECEIPT_FONT_REGULAR = 'data:font/woff2;base64,{regular}';\n"
        f"export const RECEIPT_FONT_BOLD = 'data:font/woff2;base64,{bold}';\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} (regular {len(regular) // 1024} KB, bold {len(bold) // 1024} KB base64)")


if __name__ == "__main__":
    main()
